                sb.Append("\telse\n");
                sb.Append("\t\tLOG('SCED: army ").Append(LogText(b.Army)).Append(" has no campaign AI, base ").Append(LogText(b.Id)).Append(" was not created')\n");
                sb.Append("\tend\n");
            }
            sb.Append("end\n");
            return sb.ToString();
        }

        private static string BaseStartStatement(SC2MissionBase b) =>
            b.StartMode == SC2MissionBase.StartEmpty
