using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace SC2.MapEditor.Document
{
    public sealed class SC2MissionCompileResult
    {
        public sealed class SourceMapEntry
        {
            public string StageId = "";
            public int NodeId;
            public int LineStart;
            public int LineEnd;
        }

        /// <summary>The whole _script.lua: a header region with the imports and helpers, the army block, the bases, one region per stage and the
        /// campaign entry points (OnPopulate, OnStart, OnInitCamera). Lines end with \n.</summary>
        public string Lua = "";

        public List<SC2MissionIssue> Issues = new();
        /// <summary>1-based inclusive Lua line ranges for node diagnostics and editor navigation.</summary>
        public List<SourceMapEntry> SourceMap = new();

        public bool HasErrors => SC2MissionValidator.HasErrors(Issues);
    }

    /// <summary>
    /// Turns a mission graph into the Lua of _script.lua. Every stage becomes a Start function; every node becomes a global function that
    /// does its work and then calls the functions of the nodes wired to its outputs. Nodes that wait for the game (timers, triggers,
    /// objectives, dialogue, camera moves) hand the call of their outputs to the engine as a callback instead.
    /// </summary>
    public static class SC2MissionCompiler
    {
        public const string BeginFunction = "SCED_Begin";
        public const string BasesRegion = "bases";
        public const string ArmiesRegion = "armies";
        public const string CampaignRegion = "campaign";
        private const string BasesSetupFunction = "SCED_Bases_Setup";

        /// <summary>map, when given, lets the checks name a marker, area, army or group the map does not have, and tells the compiler the order
        /// of the armies (their engine indices) and the playable area.</summary>
        public static SC2MissionCompileResult Compile(SC2MissionDocument doc, SC2MissionMapInfo map = null)
        {
            var result = new SC2MissionCompileResult();
            if (doc == null) return result;
            result.Issues = SC2MissionValidator.Validate(doc, map);
            var armies = SC2MissionArmies.Effective(doc, map);

            // The whole of _script.lua: the order of the regions is the order of the file. The army block has to come before anything that
            // reads the army locals, and the engine entry points come last.
            var sb = new StringBuilder();
            sb.Append(SC2MissionLuaMarkers.Wrap("common", Header(doc, armies)));
            sb.Append('\n');
            sb.Append(SC2MissionLuaMarkers.Wrap(ArmiesRegion, ArmiesBody(armies)));
            if (doc.Bases.Count > 0)
            {
                sb.Append('\n');
                sb.Append(SC2MissionLuaMarkers.Wrap(BasesRegion, BasesBody(doc)));
            }
            foreach (var stage in doc.Stages)
            {
                sb.Append('\n');
                sb.Append(SC2MissionLuaMarkers.Wrap(stage.Id, StageBody(doc, stage)));
            }
            sb.Append('\n');
            sb.Append(SC2MissionLuaMarkers.Wrap(CampaignRegion, CampaignBody(doc, armies, map?.PlayableArea ?? "")));
            result.Lua = sb.ToString();
            BuildSourceMap(result);
            return result;
        }

        private static void BuildSourceMap(SC2MissionCompileResult result)
        {
            var lines = result.Lua.Split(new[] { "\n" }, System.StringSplitOptions.None);
            string stage = "";
            SC2MissionCompileResult.SourceMapEntry active = null;
            for (var i = 0; i < lines.Length; i++)
            {
                var line = lines[i];
                var stageMatch = Regex.Match(line, @"^-- SCED:begin ([a-z][a-z0-9_]*) hash=");
                if (stageMatch.Success) stage = stageMatch.Groups[1].Value;
                var nodeMatch = Regex.Match(line, @"^-- #(\d+) ");
                if (nodeMatch.Success)
                {
                    if (active != null) active.LineEnd = i;
                    active = new SC2MissionCompileResult.SourceMapEntry { StageId = stage, NodeId = int.Parse(nodeMatch.Groups[1].Value, CultureInfo.InvariantCulture), LineStart = i + 1, LineEnd = lines.Length };
                    result.SourceMap.Add(active);
                }
            }
            if (active != null) active.LineEnd = lines.Length;
        }

        // ------------------------------------------------------------------ header

        private static string Header(SC2MissionDocument doc, List<SC2MissionArmyEntry> armies)
        {
            var settings = doc.Settings;
            var sb = new StringBuilder();
            sb.Append("-- Generated by the SC2 map editor mission graph. Change the graph, not this text: a region whose hash no longer matches was edited by hand.\n");
            if (!string.IsNullOrEmpty(doc.Title)) sb.Append("-- Mission: ").Append(OneLine(doc.Title)).Append('\n');
            sb.Append("local ScenarioUtils = import('/lua/sim/ScenarioUtilities.lua')\n");
            sb.Append("local ScenarioFramework = import('/lua/sim/ScenarioFramework.lua')\n");
            sb.Append("local ScenarioGameSetup = import('/lua/sim/ScenarioFramework/ScenarioGameSetup.lua')\n");
            sb.Append("local ScenarioGameCleanup = import('/lua/sim/ScenarioFramework/ScenarioGameCleanup.lua')\n");
            sb.Append("local ScenarioGameEvents = import('/lua/sim/ScenarioFramework/ScenarioGameEvents.lua')\n");
            sb.Append("local NIS = import('/lua/sim/ScenarioFramework/ScenarioGameCinematics.lua')\n");
            sb.Append("local NISSupport = import('/lua/sim/ScenarioFramework/ScenarioGameCinematicsSupport.lua')\n");
            sb.Append("local TransportUtils = import('/lua/sim/ScenarioFramework/ScenarioGameUtilsTransport.lua')\n");
            sb.Append("local ScenarioPlatoonAI = import('/lua/AI/ScenarioPlatoonAI.lua')\n");
            sb.Append("local SimObjectives = import('/lua/sim/SimObjectives.lua')\n");
            sb.Append("\n");
            sb.Append("ScenarioInfo.SCED = ScenarioInfo.SCED or { groups = {}, platoons = {}, objectives = {}, bases = {}, vars = {}, once = {}, joins = {}, stage = '' }\n");
            if (doc.Bases.Count > 0) sb.Append("ScenarioInfo.VarTable = ScenarioInfo.VarTable or {}\n");
            foreach (var v in doc.Variables)
                sb.Append("ScenarioInfo.SCED.vars[").Append(Quote(v.Name)).Append("] = ").Append(Literal(v.Type, v.Initial, doc)).Append('\n');
            sb.Append("\n");
            // A lobby slot nobody took has no army in the game, so everything that names an army looks first whether it is there.
            sb.Append("local function SCED_HasArmy(name)\n");
            sb.Append("\tlocal listed = ListArmies and ListArmies()\n");
            sb.Append("\tif not listed then return true end\n");
            sb.Append("\tlocal any = false\n");
            sb.Append("\tfor index, listedName in pairs(listed) do\n");
            sb.Append("\t\tany = true\n");
            sb.Append("\t\tif listedName == name then return true end\n");
            sb.Append("\tend\n");
            sb.Append("\treturn not any\n");
            sb.Append("end\n");
            sb.Append("\n");
            sb.Append("local function SCED_FindUnit(army, name)\n");
            sb.Append("\tlocal brain = SCED_HasArmy(army) and GetArmyBrain(army)\n");
            sb.Append("\tlocal names = brain and ScenarioInfo.UnitNames and ScenarioInfo.UnitNames[brain:GetArmyIndex()]\n");
            sb.Append("\treturn names and names[name]\n");
            sb.Append("end\n");
            sb.Append("\n");
            sb.Append("local function SCED_Group(army, name)\n");
            // a node may name several groups, separated by commas: it then gets the units of all of them in one table
            sb.Append("\tif string.find(name, ',', 1, true) then\n");
            sb.Append("\t\tlocal merged = {}\n");
            sb.Append("\t\tfor part in string.gfind(name, '[^,]+') do\n");
            sb.Append("\t\t\tlocal trimmed = string.gsub(part, '^%s*(.-)%s*$', '%1')\n");
            sb.Append("\t\t\tlocal one = ScenarioInfo.SCED.groups[army .. '/' .. trimmed]\n");
            sb.Append("\t\t\tif one then\n");
            sb.Append("\t\t\t\tfor index, unit in one do table.insert(merged, unit) end\n");
            sb.Append("\t\t\telse\n");
            sb.Append("\t\t\t\tWARN('SCED: group ', army, '/', trimmed, ' was not spawned')\n");
            sb.Append("\t\t\tend\n");
            sb.Append("\t\tend\n");
            sb.Append("\t\tif table.getn(merged) == 0 then return nil end\n");
            sb.Append("\t\treturn merged\n");
            sb.Append("\tend\n");
            sb.Append("\tlocal group = ScenarioInfo.SCED.groups[army .. '/' .. name]\n");
            sb.Append("\tif not group then WARN('SCED: group ', army, '/', name, ' was not spawned') end\n");
            sb.Append("\treturn group\n");
            sb.Append("end\n");
            sb.Append("\n");
            sb.Append("local function SCED_Platoon(army, name)\n");
            sb.Append("\tlocal platoon = ScenarioInfo.SCED.platoons[army .. '/' .. name]\n");
            sb.Append("\tif not platoon then WARN('SCED: platoon ', army, '/', name, ' was not spawned') end\n");
            sb.Append("\treturn platoon\n");
            sb.Append("end\n");
            sb.Append("\n");
            sb.Append("local function SCED_HumanCount()\n");
            sb.Append("\tlocal count = 0\n");
            sb.Append("\tfor index, brain in ArmyBrains do\n");
            sb.Append("\t\tif brain.BrainType == 'Human' then count = count + 1 end\n");
            sb.Append("\tend\n");
            sb.Append("\treturn count\n");
            sb.Append("end\n");
            sb.Append("\n");

            // The loop nodes share one small engine. A loop keeps its state in ScenarioInfo.SCED.loops, and every round runs in a thread of its
            // own, so a long loop never deepens the stack and the game goes on between two rounds.
            if (doc.Stages.Exists(st => st.Nodes.Exists(n => SC2MissionNodeCatalog.Find(n.Type)?.Category == "Loops")))
            {
                sb.Append("ScenarioInfo.SCED.loops = ScenarioInfo.SCED.loops or {}\n");
                sb.Append("ScenarioInfo.SCED.loopUnit = ScenarioInfo.SCED.loopUnit or {}\n");
                sb.Append("\n");
                sb.Append("function SCED_LoopRound(state)\n");
                sb.Append("\tif not state.active then return end\n");
                sb.Append("\tlocal token = state.token\n");
                sb.Append("\tForkThread(function()\n");
                sb.Append("\t\tif (state.i > 0 or state.delayFirst) and state.pause > 0 then WaitSeconds(state.pause) end\n");
                sb.Append("\t\twhile state.paused and state.active and state.token == token do WaitSeconds(0.5) end\n");
                sb.Append("\t\tif not state.active or state.token ~= token then return end\n");
                sb.Append("\t\tstate.i = state.i + 1\n");
                sb.Append("\t\tlocal more = true\n");
                sb.Append("\t\tif state.items then\n");
                sb.Append("\t\t\twhile state.items[state.i] and state.items[state.i]:IsDead() do state.i = state.i + 1 end\n");
                sb.Append("\t\t\tmore = state.items[state.i] ~= nil\n");
                sb.Append("\t\telseif state.count then\n");
                sb.Append("\t\t\tmore = state.i <= state.count\n");
                sb.Append("\t\telseif state.cond then\n");
                sb.Append("\t\t\tmore = state.cond() and true or false\n");
                sb.Append("\t\tend\n");
                sb.Append("\t\tif more and state.limit and state.i > state.limit then\n");
                sb.Append("\t\t\tWARN('SCED: a loop was stopped after ', state.limit, ' rounds')\n");
                sb.Append("\t\t\tmore = false\n");
                sb.Append("\t\tend\n");
                sb.Append("\t\tif not more then\n");
                sb.Append("\t\t\tstate.active = false\n");
                sb.Append("\t\t\tstate.done()\n");
                sb.Append("\t\t\treturn\n");
                sb.Append("\t\tend\n");
                sb.Append("\t\tstate.enter(state)\n");
                sb.Append("\t\tif state.auto then SCED_LoopRound(state) end\n");
                sb.Append("\tend)\n");
                sb.Append("end\n");
                sb.Append("\n");
                sb.Append("function SCED_LoopStop(state)\n");
                sb.Append("\tif state and state.active then\n");
                sb.Append("\t\tstate.active = false\n");
                sb.Append("\t\tstate.token = state.token + 1\n");
                sb.Append("\t\tstate.stopped()\n");
                sb.Append("\tend\n");
                sb.Append("end\n");
                sb.Append("\n");
            }

            if (settings.Coop)
            {
                sb.Append("-- Co-op: ").Append(settings.HumanSlots).Append(" human slot(s), the mission fails when ")
                    .Append(settings.FailWhen == SC2MissionSettings.FailAll ? "every" : settings.FailWhen == SC2MissionSettings.FailNever ? "no" : "any")
                    .Append(" player loses the commander.\n");
                sb.Append("local function SCED_WatchPlayers()\n");
                sb.Append("\tlocal seen = {}\n");
                sb.Append("\twhile not ScenarioInfo.OpEnded do\n");
                sb.Append("\t\tWaitSeconds(5)\n");
                sb.Append("\t\tlocal alive = 0\n");
                sb.Append("\t\tlocal dead = 0\n");
                sb.Append("\t\tfor index, name in { ");
                for (var i = 1; i <= Clamp(settings.HumanSlots, 1, 4); i++) sb.Append(Quote("ARMY_" + i)).Append(", ");
                sb.Append("} do\n");
                sb.Append("\t\t\tlocal brain = SCED_HasArmy(name) and GetArmyBrain(name)\n");
                sb.Append("\t\t\tif brain then\n");
                sb.Append("\t\t\t\tlocal commanders = brain:GetCurrentUnits(categories.COMMAND)\n");
                sb.Append("\t\t\t\tif commanders > 0 then seen[name] = true end\n");
                sb.Append("\t\t\t\tif seen[name] and commanders <= 0 then dead = dead + 1 else alive = alive + 1 end\n");
                sb.Append("\t\t\tend\n");
                sb.Append("\t\tend\n");
                if (settings.FailWhen == SC2MissionSettings.FailAny)
                    sb.Append("\t\tif dead > 0 then ScenarioGameCleanup.Defeat() return end\n");
                else if (settings.FailWhen == SC2MissionSettings.FailAll)
                    sb.Append("\t\tif dead > 0 and alive == 0 then ScenarioGameCleanup.Defeat() return end\n");
                sb.Append("\tend\n");
                sb.Append("end\n");
                sb.Append("\n");
            }

            // Says in the game log which armies have no units. An army with none is nearly always a mistake: nothing of it exists to be attacked
            // or to count, and the OpAI builders of a base only start when the army they target (the first one) has units.
            var hasOpAI = doc.Bases.Exists(b => b.OpAIs.Count > 0);
            sb.Append("local SCED_ArmyNames = { ");
            foreach (var a in armies) sb.Append(QuoteSingle(a.Alias)).Append(", ");
            sb.Append("}\n");
            sb.Append("\n");
            sb.Append("local function SCED_ReportArmies()\n");
            sb.Append("\tfor position, name in SCED_ArmyNames do\n");
            sb.Append("\t\tlocal index = ScenarioInfo['ARMY_' .. name]\n");
            sb.Append("\t\tlocal brain = index and ArmyBrains[index]\n");
            sb.Append("\t\tif not brain then\n");
            sb.Append("\t\t\tLOG('SCED: army ', name, ' is not in this game (an empty slot of the lobby): everything of the mission that concerns it is skipped')\n");
            sb.Append("\t\telse\n");
            sb.Append("\t\t\tlocal count = brain:GetCurrentUnits(categories.ALLUNITS)\n");
            sb.Append("\t\t\tif count > 0 then\n");
            sb.Append("\t\t\t\tLOG('SCED: army ', index, ' (', name, ') has ', count, ' units')\n");
            sb.Append("\t\t\telse\n");
            sb.Append("\t\t\t\tWARN('SCED: army ', index, ' (', name, ') has no units - give it an INITIAL group, or create one with a Spawn group node')\n");
            if (hasOpAI)
                sb.Append("\t\t\t\tif index == 1 then WARN('SCED: the OpAI of the bases is built only against army 1, which has no units, so no attack wave will be built') end\n");
            sb.Append("\t\t\tend\n");
            sb.Append("\t\tend\n");
            sb.Append("\tend\n");
            sb.Append("end\n");
            sb.Append("\n");

            // The bases are built once. A mission that asks for the difficulty builds them after the answer, because the campaign AI reads the
            // difficulty when it creates a base; otherwise they are built while the loading screen is up.
            var asksDifficulty = doc.Stages.Exists(st => st.Nodes.Exists(n => n.Type == SC2MissionExtraNodes.AskDifficultyType));
            sb.Append("local SCED_basesBuilt = false\n");
            sb.Append("function SCED_BuildBases()\n");
            sb.Append("\tif SCED_basesBuilt then return end\n");
            sb.Append("\tSCED_basesBuilt = true\n");
            if (doc.Bases.Count > 0) sb.Append('\t').Append(BasesSetupFunction).Append("()\n");
            else sb.Append("\t-- no bases\n");
            sb.Append("end\n");
            sb.Append("\n");
            // Runs while the loading screen is up (the campaign flow's funcSetup).
            sb.Append("function SCED_Setup()\n");

            if (asksDifficulty) sb.Append("\t-- the bases are built when the player has chosen the difficulty\n");
            else sb.Append("\tSCED_BuildBases()\n");
            sb.Append("end\n");
            sb.Append("\n");
            // Runs when the game is released (funcMain): the first stage starts.
            sb.Append("function ").Append(BeginFunction).Append("()\n");
            if (settings.Coop && settings.FailWhen != SC2MissionSettings.FailNever) sb.Append("\tForkThread(SCED_WatchPlayers)\n");
            sb.Append("\tSCED_ReportArmies()\n");
            sb.Append("\tForkThread(function() WaitSeconds(10) SCED_ReportArmies() end)\n");
            var first = StartStage(doc);
            if (first != null) sb.Append('\t').Append(StartFunction(first)).Append("()\n");
            else sb.Append("\t-- the mission has no stages\n");
            sb.Append("end\n");
            return sb.ToString();
        }

        // ------------------------------------------------------------------ armies and the campaign entry points

        /// <summary>The army block every campaign script opens with: the army indices, the objective list, the colours and tuning tables, the
        /// army locals, and the campaign AI the game only loads for campaign-type maps.</summary>
        private static string ArmiesBody(List<SC2MissionArmyEntry> armies)
        {
            var sb = new StringBuilder();
            foreach (var a in armies)
                sb.Append("ScenarioInfo.ARMY_").Append(a.Alias).Append(" = ").Append(a.Index.ToString(CultureInfo.InvariantCulture)).Append('\n');
            sb.Append('\n');
            sb.Append("ScenarioInfo.AssignedObjectives = {}\n");
            sb.Append("\n");
            foreach (var a in armies)
                if (a.Role != SC2MissionArmy.RolePlayer)
                    sb.Append("color_").Append(a.Alias).Append(" = ").Append(ColorTable(a.Army)).Append('\n');
            sb.Append('\n');
            foreach (var a in armies)
            {
                if (a.Role == SC2MissionArmy.RolePlayer)
                    sb.Append("TUNING_").Append(a.Alias).Append(" = {unitCap = ").Append(a.Army.UnitCap).Append(",mass = ").Append(a.Army.Mass)
                        .Append(",energy = ").Append(a.Army.Energy).Append(",research = ").Append(a.Army.Research).Append(",}\n");
                else if (a.Role == SC2MissionArmy.RoleEnemy)
                    sb.Append("TUNING_").Append(a.Alias).Append(" = {color = color_").Append(a.Alias).Append(",unitCap = ").Append(a.Army.UnitCap)
                        .Append(",massBoost = ").Append(a.Army.MassBoost).Append(",energyBoost = ").Append(a.Army.EnergyBoost).Append(",}\n");
            }
            sb.Append('\n');
            foreach (var a in armies)
                sb.Append("local ARMY_").Append(a.Alias).Append(" = ScenarioInfo.ARMY_").Append(a.Alias).Append('\n');
            sb.Append('\n');
            sb.Append("-- The armies after a lobby slot nobody took move up one place, so the fixed indices above only hold for a full lobby.\n");
            sb.Append("-- The indices are looked up by army name when the game is set up, and an army that is not in the game is nil.\n");
            sb.Append("local function SCED_ResolveArmies()\n");
            sb.Append("\tlocal listed = ListArmies and ListArmies()\n");
            sb.Append("\tlocal present = {}\n");
            sb.Append("\tlocal any = false\n");
            sb.Append("\tif listed then\n");
            sb.Append("\t\tfor index, name in pairs(listed) do present[name] = index any = true end\n");
            sb.Append("\tend\n");
            foreach (var a in armies)
            {
                sb.Append("\tif any then ScenarioInfo.ARMY_").Append(a.Alias).Append(" = present[").Append(QuoteSingle(a.Army.Name)).Append("] end\n");
                sb.Append("\tARMY_").Append(a.Alias).Append(" = ScenarioInfo.ARMY_").Append(a.Alias).Append('\n');
            }
            sb.Append("end\n");
            sb.Append('\n');
            sb.Append("LOG('*AI DEBUG: Initializing campaign')\n");
            sb.Append("-- We need to import/doscript all the campaign related stuff here\n");
            sb.Append("doscript '/lua/ai/campaign/system/CAIInitializeSystems.lua'\n");
            return sb.ToString();
        }

        private static string ColorTable(SC2MissionArmy army)
        {
            var sb = new StringBuilder("{");
            for (var i = 0; i < 3; i++)
                sb.Append('\'').Append(i < army.Colors.Length ? army.Colors[i] : "FFFFFFFF").Append("',");
            return sb.Append('}').ToString();
        }

        /// <summary>OnPopulate, OnStart and OnInitCamera as the campaign scripts have them, plus the debug hotkeys of the plain script.</summary>
        private static string CampaignBody(SC2MissionDocument doc, List<SC2MissionArmyEntry> armies, string playableArea)
        {
            var settings = doc.Settings;
            var sb = new StringBuilder();
            sb.Append("function OnPopulate()\n");
            sb.Append("\tSCED_ResolveArmies()\n");
            if (settings.Coop)
                sb.Append("\tif ScenarioInfo.Options then ScenarioInfo.Options.DoNotShareUnitCap = ").Append(settings.SharedCap ? "false" : "true").Append(" end\n");
            sb.Append("\tlocal camData = {\n");
            sb.Append("\t\tMinSpinPitch\t= 0.5,\t\t-- 0.1 = default\tThe min pitch resulting from a spin.\n");
            sb.Append("\t\tMaxZoomMult\t\t= 1.2,\t\t-- 1.1 = default\tExtra zoom out buffer so we can see the borders of the map clearly.\n");
            sb.Append("\t\tFarZoom\t\t\t= -1,\t\t-- -1 = default\t\tFarthest mouse can zoom out from terrain, measured in LOD units, -1 to ignore.\n");
            sb.Append("\t}\n");
            sb.Append("\timport('/lua/sim/SimCamera.lua').SimCamera('WorldCamera'):UpdateDefaults(camData)\n");
            if (playableArea.Length > 0)
                sb.Append("\timport('/lua/sim/ScenarioFramework.lua').SetPlayableArea(").Append(QuoteSingle(playableArea)).Append(")\n");
            sb.Append("\n");
            sb.Append("\t-- pass the data through\n");
            sb.Append("\tScenarioGameSetup.CAMPAIGN_OnPopulate(camData)\n");
            sb.Append("\n");
            sb.Append("\tLOG('----- OnPopulate: Setup Army Tuning.')\n");
            foreach (var a in armies)
            {
                sb.Append("\tif ARMY_").Append(a.Alias).Append(" then\n");
                if (a.Role == SC2MissionArmy.RolePlayer)
                    sb.Append("\t\tScenarioGameSetup.SetupPlayerArmy(\tARMY_").Append(a.Alias).Append(", TUNING_").Append(a.Alias).Append(")\n");
                else if (a.Role == SC2MissionArmy.RoleEnemy)
                    sb.Append("\t\tScenarioGameSetup.SetupNonPlayerArmy(\tARMY_").Append(a.Alias).Append(", TUNING_").Append(a.Alias).Append(")\n");
                else
                    sb.Append("\t\tScenarioGameSetup.SetupGenericArmy(\tARMY_").Append(a.Alias).Append(", color_").Append(a.Alias).Append(")\n");
                sb.Append("\tend\n");
            }
            var unlocked = armies.FindAll(a => a.Role == SC2MissionArmy.RoleEnemy && a.Army.UnlockResearch);
            if (unlocked.Count > 0)
            {
                sb.Append("\n");
                sb.Append("\t-- the AI builds nothing that fights until its research is unlocked\n");
                foreach (var a in unlocked) sb.Append("\tif ARMY_").Append(a.Alias).Append(" then UnlockAllResearch(ARMY_").Append(a.Alias).Append(") end\n");
            }
            sb.Append("end\n");
            sb.Append("\n");
            sb.Append("function OnStart(self)\n");
            sb.Append("\tlocal strMusic = 'SC2/MUSIC/MP/Conditional_Music'\n");
            sb.Append("\tLOG('MP: Music: [', strMusic, ']')\n");
            sb.Append("\tSync.PlayMusic = strMusic\n");
            sb.Append("\tScenarioGameSetup.CAMPAIGN_OnStart()\n");
            sb.Append("end\n");
            sb.Append("\n");
            sb.Append("function OnInitCamera(scen)\n");
            sb.Append("\tlocal data = {\n");
            sb.Append("\t\tfuncSetup\t\t= SCED_Setup,\t\t-- called while the load screen is up\n");
            sb.Append("\t\tfuncMain\t\t= ").Append(BeginFunction).Append(",\t\t-- called when the game is released\n");
            if (playableArea.Length > 0) sb.Append("\t\tareaStart\t\t= ").Append(QuoteSingle(playableArea)).Append(",\n");
            sb.Append("\t}\n");
            sb.Append("\n");
            sb.Append("\tScenarioGameSetup.CAMPAIGN_OnInitCamera(data)\n");
            sb.Append("end\n");
            sb.Append("\n");
            foreach (var hotkey in new[] { ("OnShiftF3", "GroupPicker_Increment"), ("OnCtrlF3", "GroupPicker_Decrement"), ("OnShiftF4", "TestPicker_Increment"), ("OnCtrlF4", "TestPicker_Decrement"), ("OnShiftF5", "ExecuteCurrentTest") })
            {
                sb.Append("function ").Append(hotkey.Item1).Append("()\n");
                sb.Append("\timport('/lua/sim/ScenarioFramework/ScenarioTesting.lua').").Append(hotkey.Item2).Append("()\n");
                sb.Append("end\n\n");
            }
            return sb.ToString();
        }

        /// <summary>A Lua string literal in single quotes, the way the scripts of the game write area and marker names.</summary>
        private static string QuoteSingle(string text) => "'" + Escape(text).Replace("'", "\\'") + "'";

        /// <summary>The stage a run begins with: the settings' test stage when it exists, otherwise the first one.</summary>
        public static SC2MissionStage StartStage(SC2MissionDocument doc)
        {
            if (!string.IsNullOrEmpty(doc.Settings.TestStartStage))
            {
                var test = doc.FindStage(doc.Settings.TestStartStage);
                if (test != null) return test;
            }
            return doc.Stages.Count > 0 ? doc.Stages[0] : null;
        }

