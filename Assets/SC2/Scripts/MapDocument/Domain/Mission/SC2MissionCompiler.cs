                sb.Append("\t\tScenarioInfo.SCED.bases[").Append(Quote(b.Id)).Append("] = base\n");
                sb.Append("\t\tLOG('SCED: base ").Append(LogText(b.Id)).Append(" created for ").Append(LogText(b.Army)).Append(", ").Append(b.OpAIs.Count.ToString(CultureInfo.InvariantCulture)).Append(" OpAI')\n");
                foreach (var o in b.OpAIs)
                {
                    sb.Append("\t\topai = base:AddOpAI(").Append(Quote(o.Type)).Append(", ").Append(Quote(o.Name)).Append(", {})\n");
                    if (o.Thread == SC2MissionOpAI.RandomizedPoints)
                    {
                        sb.Append("\t\topai:SetPlatoonThread(").Append(Quote(o.Thread)).Append(", { PatrolChain = ")
                            .Append(Quote(o.Chains.Count > 0 ? o.Chains[0] : "")).Append(", })\n");
                    }
                    else
                    {
                        sb.Append("\t\topai:SetPlatoonThread(").Append(Quote(o.Thread)).Append(", { AnnounceRoute = true, PatrolChains = { ");
                        foreach (var c in o.Chains) sb.Append(Quote(c)).Append(", ");
                        sb.Append("}, })\n");
                    }
                    if (o.ChildCount > 0) sb.Append("\t\topai:SetChildCount(").Append(o.ChildCount.ToString(CultureInfo.InvariantCulture)).Append(")\n");
                    sb.Append("\t\topai:SetMaxActivePlatoons(").Append(o.MaxPlatoons.ToString(CultureInfo.InvariantCulture)).Append(")\n");
                    if (o.AttackDelay > 0) sb.Append("\t\topai:SetAttackDelay(").Append(o.AttackDelay.ToString(CultureInfo.InvariantCulture)).Append(")\n");
