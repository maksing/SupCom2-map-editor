        private static string StageBody(SC2MissionDocument doc, SC2MissionStage stage)
        {
            var sb = new StringBuilder();
            sb.Append("function ").Append(StartFunction(stage)).Append("()\n");
            sb.Append("\tScenarioInfo.SCED.stage = ").Append(Quote(stage.Id)).Append('\n');
            AppendCalls(sb, stage, SC2MissionStage.StartNodeId, SC2MissionStage.StartPort);
            sb.Append("end\n");

            foreach (var node in stage.Nodes)
            {
                var def = SC2MissionNodeCatalog.Find(node.Type);
                if (def == null || def.IsComment) continue;
                sb.Append('\n');
                AppendNode(sb, doc, stage, node, def);
            }
            return sb.ToString();
        }

        private static void AppendNode(StringBuilder sb, SC2MissionDocument doc, SC2MissionStage stage, SC2MissionNode node, SC2MissionNodeDef def)
        {
            sb.Append("-- #").Append(node.Id).Append(' ').Append(def.Title).Append('\n');

            // The functions the outputs call; the engine invokes these for the nodes that defer.
            foreach (var port in SC2MissionNodeCatalog.PortsOf(def, node))
            {
                sb.Append("function ").Append(PortFunction(stage, node.Id, port)).Append("()\n");
                AppendCalls(sb, stage, node.Id, port);
                sb.Append("end\n");
            }

            // One function per input: a wire that ends at an input runs that function.
            foreach (var input in SC2MissionNodeCatalog.InputsOf(def, node))
            {
                sb.Append("function ").Append(InputFunction(stage, node.Id, input)).Append("()\n");
                AppendNodeBody(sb, doc, stage, node, def, input);
                sb.Append("end\n");
            }
        }

        private static void AppendNodeBody(StringBuilder sb, SC2MissionDocument doc, SC2MissionStage stage, SC2MissionNode node, SC2MissionNodeDef def, string input)
        {
            if (def.Objective != null)
            {
                AppendObjective(sb, stage, node, def.Objective.Function,
                    def.Objective.Action == null ? null : Expand(def.Objective.Action, doc, stage, node, def),
                    Expand(def.Objective.Target, doc, stage, node, def), def.Objective.NeedsGroup);
                return;
            }
            if (def.Template != null)
            {
                AppendTemplate(sb, doc, stage, node, def, input);
                return;
            }
            switch (node.Type)
            {
                case SC2MissionNodeCatalog.Timer:
                    sb.Append("\tScenarioFramework.CreateTimerTrigger(").Append(PortFunction(stage, node.Id, "fired")).Append(", ")
                        .Append(NumberExpr(node.GetParam("seconds"))).Append(")\n");
                    break;
                case SC2MissionNodeCatalog.AreaEntered:
                    sb.Append("\tScenarioFramework.CreateAreaTrigger(").Append(PortFunction(stage, node.Id, "entered")).Append(", ")
                        .Append(Quote(node.GetParam("area"))).Append(", ").Append(node.GetParam("categories", "categories.ALLUNITS")).Append(", ")
                        .Append(Bool(node.GetParam("once"))).Append(", false, GetArmyBrain(").Append(Quote(node.GetParam("army"))).Append("), 1)\n");
                    break;
                case SC2MissionNodeCatalog.UnitKilled:
                    sb.Append("\tlocal unit = SCED_FindUnit(").Append(Quote(node.GetParam("army"))).Append(", ").Append(Quote(node.GetParam("unit"))).Append(")\n");
                    sb.Append("\tif unit then\n");
                    sb.Append("\t\tScenarioFramework.CreateUnitDeathTrigger(").Append(PortFunction(stage, node.Id, "killed")).Append(", unit)\n");
                    sb.Append("\telse\n");
                    sb.Append("\t\tLOG('SCED: unit ").Append(LogText(node.GetParam("army") + "/" + node.GetParam("unit"))).Append(" does not exist')\n");
                    sb.Append("\tend\n");
                    break;
                case SC2MissionNodeCatalog.GroupKilled:
                    AppendGroupLookup(sb, node);
                    sb.Append("\tif group then\n");
                    sb.Append("\t\tScenarioFramework.CreateGroupDeathTrigger(").Append(PortFunction(stage, node.Id, "killed")).Append(", group)\n");
                    sb.Append("\telse\n");
                    sb.Append("\t\tLOG('SCED: group ").Append(LogText(GroupKey(node))).Append(" was not spawned')\n");
                    sb.Append("\tend\n");
                    break;
                case SC2MissionNodeCatalog.SpawnGroup when node.GetParam("group").Contains(","):
                    // several groups: each is created on its own and kept under its own key, so a later node may name any of them
                    foreach (var name in SC2MissionNodeCatalog.SplitList(node.GetParam("group")))
                    {
                        var key = Quote(node.GetParam("army") + "/" + name);
                        sb.Append("\tdo\n");
                        sb.Append("\t\tlocal ok, group = pcall(ScenarioUtils.CreateArmyGroup, ").Append(Quote(node.GetParam("army"))).Append(", ").Append(Quote(name)).Append(")\n");
                        sb.Append("\t\tif ok and group and table.getn(group) > 0 then\n");
                        sb.Append("\t\t\tScenarioInfo.SCED.groups[").Append(key).Append("] = group\n");
                        sb.Append("\t\t\tLOG('SCED: spawned ', table.getn(group), ' units of ").Append(LogText(node.GetParam("army") + "/" + name)).Append("')\n");
                        sb.Append("\t\telse\n");
                        sb.Append("\t\t\tWARN('SCED: the group ").Append(LogText(node.GetParam("army") + "/" + name)).Append(" created no units: ', ok and 'it is empty' or group)\n");
                        sb.Append("\t\tend\n");
                        sb.Append("\tend\n");
                    }
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                case SC2MissionNodeCatalog.SpawnGroup:
                    // CreateArmyGroup raises an error for a group that does not exist or holds no units; the log gets the reason and the chain goes on.
                    sb.Append("\tlocal ok, group = pcall(ScenarioUtils.CreateArmyGroup, ").Append(Quote(node.GetParam("army"))).Append(", ").Append(Quote(node.GetParam("group"))).Append(")\n");
                    sb.Append("\tif ok and group and table.getn(group) > 0 then\n");
                    sb.Append("\t\tScenarioInfo.SCED.groups[").Append(Quote(GroupKey(node))).Append("] = group\n");
                    sb.Append("\t\tLOG('SCED: spawned ', table.getn(group), ' units of ").Append(LogText(GroupKey(node))).Append("')\n");
                    sb.Append("\telse\n");
                    sb.Append("\t\tWARN('SCED: the group ").Append(LogText(GroupKey(node))).Append(" created no units: ', ok and 'it is empty' or group)\n");
                    sb.Append("\tend\n");
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                case SC2MissionNodeCatalog.GiveOrder:
                    AppendGroupLookup(sb, node);
                    sb.Append("\tif group then\n");
                    AppendOrder(sb, node);
                    sb.Append("\telse\n");
                    sb.Append("\t\tLOG('SCED: group ").Append(LogText(GroupKey(node))).Append(" was not spawned')\n");
                    sb.Append("\tend\n");
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                case SC2MissionNodeCatalog.ObjectiveKill:
                    AppendObjective(sb, stage, node, "SimObjectives.Kill", null, "{ Units = group }", true);
                    break;
                case SC2MissionNodeCatalog.ObjectiveProtect:
                    AppendObjective(sb, stage, node, "SimObjectives.Protect", null,
                        "{ Units = group, MarkUnits = true, Timer = " + NumberExpr(node.GetParam("seconds")) + " }", true);
                    break;
                case SC2MissionNodeCatalog.ObjectiveCapture:
                    AppendObjective(sb, stage, node, "SimObjectives.Capture", null, "{ Units = group, MarkUnits = true }", true);
                    break;
                case SC2MissionNodeCatalog.ObjectiveArea:
                    AppendObjective(sb, stage, node, "SimObjectives.CategoriesInArea", "'move'",
                        "{ Requirements = { { Area = " + Quote(node.GetParam("area")) + ", Category = " + node.GetParam("categories", "categories.ALLUNITS") +
                        ", CompareOp = " + Quote(node.GetParam("compare", ">=")) + ", Value = " + NumberExpr(node.GetParam("count")) +
                        ", ArmyIndex = GetArmyBrain(" + Quote(node.GetParam("army")) + "):GetArmyIndex() }, }, }", false);
                    break;
                case SC2MissionNodeCatalog.ObjectiveTimer:
                    AppendObjective(sb, stage, node, "SimObjectives.Timer", null,
                        "{ Timer = " + NumberExpr(node.GetParam("seconds")) + ", ExpireResult = " + Quote(node.GetParam("result", "complete")) + " }", false);
                    break;
                case SC2MissionNodeCatalog.ObjectiveResolve:
                    sb.Append("\tlocal objective = ScenarioInfo.SCED.objectives[").Append(Quote(stage.Id + "/N" + node.GetParam("node"))).Append("]\n");
                    sb.Append("\tif objective then objective:ManualResult(").Append(node.GetParam("result") == "failed" ? "false" : "true").Append(") end\n");
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                case SC2MissionNodeCatalog.Dialogue:
                    AppendDialogue(sb, stage, node);
                    break;
                case SC2MissionNodeCatalog.CutsceneStart:
                    // The game's own NIS system sets up the bars, the input lock and the saved camera that the end node gives back.
                    sb.Append("\tForkThread(function()\n");
                    sb.Append("\t\tNIS.StartNIS_Standard(nil, true, true)\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    sb.Append("\tend)\n");
                    break;
                case SC2MissionNodeCatalog.CameraMove:
                    // The move waits for the camera, so it runs in its own thread.
                    sb.Append("\tForkThread(function()\n");
                    sb.Append("\t\tNIS.MoveTo(").Append(Quote(node.GetParam("marker"))).Append(", ").Append(NumberExpr(node.GetParam("seconds"))).Append(")\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "done")).Append("()\n");
                    sb.Append("\tend)\n");
                    break;
                case SC2MissionNodeCatalog.CutsceneEnd:
                    // Ending restores the camera, shows the interface again and unlocks the input; it waits while the camera flies back.
                    sb.Append("\tForkThread(function()\n");
                    sb.Append("\t\tNIS.EndNIS_Standard(nil, false, 2)\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    sb.Append("\tend)\n");
                    break;
                case SC2MissionNodeCatalog.SetVariable:
                {
                    var variable = doc.FindVariable(node.GetParam("variable"));
                    var key = "ScenarioInfo.SCED.vars[" + Quote(node.GetParam("variable")) + "]";
                    var value = Literal(variable?.Type ?? SC2MissionVariable.Number, node.GetParam("value"), doc);
                    sb.Append('\t').Append(key).Append(" = ").Append(node.GetParam("op") == "add" ? "(" + key + " or 0) + " + value : value).Append('\n');
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                }
                case SC2MissionNodeCatalog.Branch:
                {
                    var variable = doc.FindVariable(node.GetParam("variable"));
                    var op = System.Array.IndexOf(SC2MissionNodeCatalog.CompareOps, node.GetParam("compare")) >= 0 ? node.GetParam("compare") : "==";
                    sb.Append("\tif ScenarioInfo.SCED.vars[").Append(Quote(node.GetParam("variable"))).Append("] ").Append(op).Append(' ')
                        .Append(Literal(variable?.Type ?? SC2MissionVariable.Number, node.GetParam("value"), doc)).Append(" then\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "true")).Append("()\n");
                    sb.Append("\telse\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "false")).Append("()\n");
                    sb.Append("\tend\n");
                    break;
                }
                case SC2MissionNodeCatalog.CoopBranch:
                    sb.Append("\tif SCED_HumanCount() > 1 then\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "coop")).Append("()\n");
                    sb.Append("\telse\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "solo")).Append("()\n");
                    sb.Append("\tend\n");
                    break;
                case SC2MissionNodeCatalog.BaseStart:
                {
                    var b = doc.FindBase(node.GetParam("base"));
                    sb.Append("\tlocal base = ScenarioInfo.SCED.bases[").Append(Quote(node.GetParam("base"))).Append("]\n");
                    sb.Append("\tif base then ").Append(b != null ? BaseStartStatement(b) : "base:StartNonZeroBase(0)").Append(" end\n");
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                }
                case SC2MissionNodeCatalog.OpAISet:
                    sb.Append("\tlocal base = ScenarioInfo.SCED.bases[").Append(Quote(node.GetParam("base"))).Append("]\n");
                    sb.Append("\tlocal opai = base and base:GetOpAI(").Append(Quote(node.GetParam("opai"))).Append(")\n");
                    sb.Append("\tif opai then opai:").Append(node.GetParam("state") == "disable" ? "Disable" : "Enable").Append("() end\n");
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                case SC2MissionNodeCatalog.AdvanceStage:
                    sb.Append("\tSCED_").Append(node.GetParam("stage")).Append("_Start()\n");
                    break;
                case SC2MissionNodeCatalog.Victory:
                    sb.Append("\tScenarioGameCleanup.Victory()\n");
                    break;
                case SC2MissionNodeCatalog.Defeat:
                    sb.Append("\tScenarioGameCleanup.Defeat()\n");
                    break;
                case SC2MissionNodeCatalog.RawLua:
                    foreach (var line in SC2MissionLuaMarkers.Normalize(node.GetParam("code")).Split('\n'))
                        sb.Append('\t').Append(line).Append('\n');
                    sb.Append("\t").Append(PortFunction(stage, node.Id, "out")).Append("()\n");
                    break;
                case "sequence":
                    // Every output in turn, one after the other.
                    foreach (var port in SC2MissionNodeCatalog.PortsOf(def, node))
                        sb.Append('\t').Append(PortFunction(stage, node.Id, port)).Append("()\n");
                    break;
                case "sequence_timed":
                {
                    sb.Append("\tForkThread(function()\n");
                    var ports = SC2MissionNodeCatalog.PortsOf(def, node);
                    for (var i = 0; i < ports.Length; i++)
                    {
                        if (i > 0) sb.Append("\t\tWaitSeconds(").Append(NumberExpr(node.GetParam("seconds", "1"))).Append(")\n");
                        sb.Append("\t\t").Append(PortFunction(stage, node.Id, ports[i])).Append("()\n");
                    }
                    sb.Append("\tend)\n");
                    break;
                }
                case "switch_variable":
                {
                    var cases = new List<string>();
                    foreach (var part in node.GetParam("cases").Split(',')) if (part.Trim().Length > 0) cases.Add(part.Trim());
                    if (cases.Count == 0) cases.Add("");
                    if (cases.Count > SC2MissionNodeCatalog.MaxCounted) cases.RemoveRange(SC2MissionNodeCatalog.MaxCounted, cases.Count - SC2MissionNodeCatalog.MaxCounted);
                    sb.Append("\tlocal value = tostring(ScenarioInfo.SCED.vars[").Append(Quote(node.GetParam("variable"))).Append("])\n");
                    for (var i = 0; i < cases.Count; i++)
                    {
                        sb.Append(i == 0 ? "\tif" : "\telseif").Append(" value == ").Append(Quote(cases[i])).Append(" then\n");
                        sb.Append("\t\t").Append(PortFunction(stage, node.Id, (i + 1).ToString(CultureInfo.InvariantCulture))).Append("()\n");
                    }
                    sb.Append("\telse\n");
                    sb.Append("\t\t").Append(PortFunction(stage, node.Id, "other")).Append("()\n");
                    sb.Append("\tend\n");
                    break;
                }
            }
        }

        // ------------------------------------------------------------------ templates

        private static readonly Regex PlaceholderPattern = new(@"\{([A-Za-z0-9_]+)(?::([A-Za-z0-9_,]+))?\}", RegexOptions.Compiled);

        private static void AppendTemplate(StringBuilder sb, SC2MissionDocument doc, SC2MissionStage stage, SC2MissionNode node, SC2MissionNodeDef def, string input = SC2MissionNodeCatalog.DefaultInput)
        {
            var hasOwn = def.InputTemplates != null && def.InputTemplates.TryGetValue(input, out var own);
            var template = hasOwn ? def.InputTemplates[input] : def.Template;
            var body = Expand(template, doc, stage, node, def, input);
            foreach (var line in body.Split('\n')) sb.Append('\t').Append(line).Append('\n');
            // A node that does not wait calls its only output itself, unless the template hands that call to something else. The inputs that
            // have a template of their own (a gate's open and close) only change the node's state.
            if (!hasOwn && !def.Defers && System.Array.IndexOf(SC2MissionNodeCatalog.PortsOf(def, node), "out") >= 0 && !template.Contains("{cb:out}"))
                sb.Append('\t').Append(PortFunction(stage, node.Id, "out")).Append("()\n");
        }

        /// <summary>Fills in the placeholders of a template from the node's parameters; see SC2MissionExtraNodes for the list.</summary>
        private static string Expand(string template, SC2MissionDocument doc, SC2MissionStage stage, SC2MissionNode node, SC2MissionNodeDef def, string input = SC2MissionNodeCatalog.DefaultInput)
        {
            return PlaceholderPattern.Replace(template, m =>
            {
                var name = m.Groups[1].Value;
                var arg = m.Groups[2].Success ? m.Groups[2].Value : null;
                if (arg == null)
                {
                    if (name == "node") return Quote(stage.Id + "/N" + node.Id);
                    if (name == "input") return Quote(input);
                    if (name == "groupkey") return Quote(GroupKey(node));
                    // the unit the for-each loop named by the node's "loop" parameter is working on
                    if (name == "loopunit") return "ScenarioInfo.SCED.loopUnit[" + Quote(stage.Id + "/N" + node.GetParam("loop")) + "]";
                    var plain = SC2MissionNodeCatalog.FindParam(def, name);
                    return plain == null ? m.Value : ParamValue(plain, node.GetParam(name, plain.Default));
                }
                if (name == "cb") return PortFunction(stage, node.Id, arg);
                var param = SC2MissionNodeCatalog.FindParam(def, arg);
                if (param == null) return m.Value;
                var value = node.GetParam(arg, param.Default) ?? "";
                switch (name)
                {
                    case "raw": return value;
                    // a value written the way the type of the variable of the node asks for (the variable parameter is called "variable")
                    case "varvalue": return Literal(doc.FindVariable(node.GetParam("variable"))?.Type ?? SC2MissionVariable.Number, value, doc);
                    case "brain": return "GetArmyBrain(" + Quote(value) + ")";
                    case "armyindex": return "GetArmyBrain(" + Quote(value) + "):GetArmyIndex()";
                    case "pos": return "ScenarioUtils.MarkerToPosition(" + Quote(value) + ")";
                    case "opt": return value.Length == 0 ? "nil" : Quote(value);
                    case "list": return LuaList(value, item => Quote(item));
                    case "brains": return LuaList(value, item => "GetArmyBrain(" + Quote(item) + ")");
                    case "positions": return LuaList(value, item => "ScenarioUtils.MarkerToPosition(" + Quote(item) + ")");
                    case "map":
                    {
                        var index = param.Choices == null ? -1 : System.Array.IndexOf(param.Choices, value);
                        return index >= 0 && param.Lua != null && index < param.Lua.Length ? param.Lua[index] : "nil";
                    }
                    default: return m.Value;
                }
            });
        }

        /// <summary>A parameter written as a Lua value: a number (or a variable), true/false, a categories expression, or a string.</summary>
        private static string ParamValue(SC2MissionParamDef p, string value)
        {
            switch (p.Kind)
            {
                case SC2MissionParamKind.Number: return NumberExpr(value);
                case SC2MissionParamKind.Bool: return Bool(value);
                case SC2MissionParamKind.Categories:
                case SC2MissionParamKind.Code: return value ?? "";
                default: return Quote(value);
            }
        }

        private static string LuaList(string commaSeparated, System.Func<string, string> item)
        {
            var parts = new List<string>();
            foreach (var part in (commaSeparated ?? "").Split(','))
            {
                var trimmed = part.Trim();
                if (trimmed.Length > 0) parts.Add(item(trimmed));
            }
            return parts.Count == 0 ? "{}" : "{ " + string.Join(", ", parts) + " }";
        }

        private static void AppendGroupLookup(StringBuilder sb, SC2MissionNode node)
        {
            // several groups: the helper joins their units; one group is read as it always was
            if (node.GetParam("group").Contains(","))
                sb.Append("\tlocal group = SCED_Group(").Append(Quote(node.GetParam("army"))).Append(", ")
                    .Append(Quote(string.Join(",", SC2MissionNodeCatalog.SplitList(node.GetParam("group"))))).Append(")\n");
            else
                sb.Append("\tlocal group = ScenarioInfo.SCED.groups[").Append(Quote(GroupKey(node))).Append("]\n");
        }

        private static void AppendOrder(StringBuilder sb, SC2MissionNode node)
        {
            var chain = Quote(node.GetParam("chain"));
            switch (node.GetParam("order"))
            {
                case "move":
                    sb.Append("\t\tfor index, position in ScenarioUtils.ChainToPositions(").Append(chain).Append(") do IssueMove(group, position) end\n");
                    break;
                case "attack-move":
                    sb.Append("\t\tfor index, position in ScenarioUtils.ChainToPositions(").Append(chain).Append(") do IssueAggressiveMove(group, position) end\n");
                    break;
                default:
                    sb.Append("\t\tScenarioFramework.GroupPatrolChain(group, ").Append(chain).Append(")\n");
                    break;
            }
        }

        /// <summary>An objective that watches a spawned group (needsGroup) or stands alone. The result goes to the completed or failed output.</summary>
        private static void AppendObjective(StringBuilder sb, SC2MissionStage stage, SC2MissionNode node, string function, string action, string target, bool needsGroup)
        {
            if (needsGroup)
            {
                AppendGroupLookup(sb, node);
                sb.Append("\tif not group then\n");
                sb.Append("\t\tLOG('SCED: group ").Append(LogText(GroupKey(node))).Append(" was not spawned')\n");
                sb.Append("\t\treturn\n");
                sb.Append("\tend\n");
            }
            sb.Append("\tlocal objective = ").Append(function).Append('(').Append(Quote(node.GetParam("kind", "primary"))).Append(", 'incomplete', ")
                .Append(Quote(node.GetParam("title"))).Append(", ").Append(Quote(node.GetParam("description"))).Append(", ");
            if (action != null) sb.Append(action).Append(", ");
            sb.Append(target).Append(")\n");
            sb.Append("\tScenarioInfo.SCED.objectives[").Append(Quote(stage.Id + "/N" + node.Id)).Append("] = objective\n");
            sb.Append("\ttable.insert(ScenarioInfo.AssignedObjectives, objective)\n");
            sb.Append("\tobjective:AddResultCallback(function(result)\n");
            sb.Append("\t\tif result then\n");
            sb.Append("\t\t\t").Append(PortFunction(stage, node.Id, "completed")).Append("()\n");
            sb.Append("\t\telse\n");
            sb.Append("\t\t\t").Append(PortFunction(stage, node.Id, "failed")).Append("()\n");
            sb.Append("\t\tend\n");
            sb.Append("\tend)\n");
        }

        /// <summary>With a video file the line goes through the game's dialogue queue (subtitles, voice, portrait); without one it is a plain
        /// text message, because the queue skips lines that have no video.</summary>
        private static void AppendDialogue(StringBuilder sb, SC2MissionStage stage, SC2MissionNode node)
        {
            var done = PortFunction(stage, node.Id, "done");
            var seconds = NumberExpr(node.GetParam("seconds"));
            if (node.GetParam("video").Length > 0)
            {
                sb.Append("\tScenarioFramework.Dialogue({ { speaker = ").Append(Quote(node.GetParam("speaker"))).Append(", text = ").Append(Quote(node.GetParam("text")))
                    .Append(", vid = ").Append(Quote(node.GetParam("video"))).Append(", bank = ").Append(Quote(node.GetParam("bank")))
                    .Append(", cue = ").Append(Quote(node.GetParam("cue"))).Append(", forced_duration = ").Append(seconds).Append(" }, }, ").Append(done).Append(")\n");
                return;
            }
            var line = node.GetParam("speaker").Length > 0 ? node.GetParam("speaker") + ": " + node.GetParam("text") : node.GetParam("text");
            sb.Append("\tSync.PrintText = Sync.PrintText or {}\n");
            sb.Append("\ttable.insert(Sync.PrintText, { text = ").Append(Quote(line)).Append(", size = 16, color = 'ffffffff', duration = ").Append(seconds)
                .Append(", location = 'leftbottom' })\n");
            sb.Append("\tScenarioFramework.CreateTimerTrigger(").Append(done).Append(", ").Append(seconds).Append(")\n");
        }

        private static void AppendCalls(StringBuilder sb, SC2MissionStage stage, int fromNode, string port)
        {
            var any = false;
            foreach (var e in stage.Edges)
            {
                if (e.FromNode != fromNode || e.FromPort != port) continue;
                var target = stage.FindNode(e.ToNode);
                if (target == null) continue;
                if (System.Array.IndexOf(SC2MissionNodeCatalog.InputsOf(SC2MissionNodeCatalog.Find(target.Type), target), e.ToPort ?? SC2MissionNodeCatalog.DefaultInput) < 0) continue;
                sb.Append('\t').Append(InputFunction(stage, e.ToNode, e.ToPort ?? SC2MissionNodeCatalog.DefaultInput)).Append("()\n");
                any = true;
            }
            if (!any) sb.Append("\t-- nothing is connected to '").Append(port).Append("'\n");
        }

        // ------------------------------------------------------------------ literals

        public static string StartFunction(SC2MissionStage stage) => "SCED_" + stage.Id + "_Start";
        private static string NodeFunction(SC2MissionStage stage, int id) => "SCED_" + stage.Id + "_N" + id;
        private static string PortFunction(SC2MissionStage stage, int id, string port) => NodeFunction(stage, id) + "_" + port;
        private static string InputFunction(SC2MissionStage stage, int id, string input) =>
            input == SC2MissionNodeCatalog.DefaultInput ? NodeFunction(stage, id) : NodeFunction(stage, id) + "_in_" + input;
        private static string GroupKey(SC2MissionNode node) => node.GetParam("army") + "/" + node.GetParam("group");

        private static string Bool(string value) => value == "true" ? "true" : "false";
        private static int Clamp(int value, int min, int max) => value < min ? min : value > max ? max : value;

        /// <summary>A number parameter: a literal, or $name for the value of a mission variable.</summary>
        private static string NumberExpr(string value)
        {
            if (value != null && value.StartsWith("$")) return "(ScenarioInfo.SCED.vars[" + Quote(value.Substring(1)) + "] or 0)";
            return double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var n) ? n.ToString("0.###", CultureInfo.InvariantCulture) : "0";
        }

        /// <summary>A Lua value of a variable's type from the text a user typed; $name reads another variable.</summary>
        private static string Literal(string type, string text, SC2MissionDocument doc)
        {
            if (text != null && text.StartsWith("$")) return "ScenarioInfo.SCED.vars[" + Quote(text.Substring(1)) + "]";
            switch (type)
            {
                case SC2MissionVariable.Text: return Quote(text);
                case SC2MissionVariable.Bool: return text == "true" ? "true" : "false";
                default: return NumberExpr(text);
            }
        }

        private static string OneLine(string text) => (text ?? "").Replace("\r", " ").Replace("\n", " ");

        /// <summary>The text inside a Lua string quoted with single quotes in a LOG call.</summary>
        private static string LogText(string text) => Escape(text).Replace("'", "\\'");

        /// <summary>A Lua double-quoted string literal.</summary>
        public static string Quote(string text) => "\"" + Escape(text).Replace("\"", "\\\"") + "\"";

        private static string Escape(string text)
        {
            var sb = new StringBuilder();
            foreach (var c in text ?? "")
            {
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < ' ') sb.Append("\\").Append(((int)c).ToString("000", CultureInfo.InvariantCulture));
                        else sb.Append(c);
                        break;
                }
            }
            return sb.ToString();
        }
