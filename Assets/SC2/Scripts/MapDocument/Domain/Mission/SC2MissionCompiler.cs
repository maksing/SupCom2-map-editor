                sb.Append("\telseif GetArmyBrain(").Append(Quote(b.Army)).Append(").CampaignAISystem then\n");
                sb.Append("\t\tbase = GetArmyBrain(").Append(Quote(b.Army)).Append(").CampaignAISystem:AddBaseManager(")
                    .Append(Quote(b.Id)).Append(", ").Append(Quote(b.Marker)).Append(", ").Append(b.Radius.ToString(CultureInfo.InvariantCulture)).Append(", { ");
