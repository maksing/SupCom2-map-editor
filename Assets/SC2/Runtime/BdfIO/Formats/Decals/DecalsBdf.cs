using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using BdfIO.Core;

namespace BdfIO.Formats.Decals
{
/// <summary>
/// decals.bdf — a baked/merged decal mesh + atlas texture references, NOT a
/// 1:1 serialization of the individually-authored decals in the map's
/// editor-side .decals.tdf/.decalmats.tdf (those hold per-decal Pos/Orient/
/// Scale/Material name; this format holds one already-projected, already-
/// atlas-packed triangle mesh covering all of them). Structure confirmed by
/// direct inspection of real vanilla decals.win.bdf files (byte-math +
/// cross-referencing baked vertex ScaleOffset values against decalmats.tdf's
/// named atlas rectangles — see the Objects/BDF research notes) rather than
/// from any known spec, so treat field names as "best current understanding"
/// the same way the rest of BdfIO.Formats does for reverse-engineered
/// layouts.
///
/// Layout (16-byte header + two variable-length C-strings, immediately
/// followed by an EDH/EDB spatial block, then a SEPARATE geometry
/// sub-file located via the container's TrailingData — same convention
/// terrain.bdf/collision.bdf already use):
///
///   int32 Version                (=3, always)
///   int32 DiffuseAtlasPathOffset (=16, always — right after this header)
///   int32 NormalAtlasPathOffset  (= DiffuseAtlasPathOffset + strlen(diffuse)+1;
///                                   these are tightly-packed C-strings, NOT
///                                   fixed-width slots — a common mistake to
///                                   make from sampling only same-length paths)
///   int32 ExtraDataOffset        (= NormalAtlasPathOffset + strlen(normal)+1,
///                                   or -1 if the map has no decals at all)
///   [DiffuseAtlasPathOffset]  NUL-terminated diffuse atlas texture path
///   [NormalAtlasPathOffset]   NUL-terminated normal atlas texture path
///   [ExtraDataOffset, geometryHeaderOffset)  EDH + EDB tree + zero alignment
///     padding. The layout is the same 108-byte EDH and 56-byte node format
///     used by terrain/collision2. It is preserved verbatim on an unchanged
///     round-trip; authored geometry is repacked and regenerated by
///     DecalsSpatialBuilder before serialization.
///
/// Geometry sub-file, located at BdfContainer.TrailingData's SECOND uint32
/// (exactly the same "[0, SubFileHeaderStart]" convention terrain.bdf/
/// collision2.bdf already use — NOT the container's OffsetTable, which
/// instead marks pointer-FIELD positions for platform/endian relocation):
///
///   int32 Version       (=1, always)
///   int32 VertexCount
///   int32 VertexOffset  (relative to this 20-byte header's own start; -1
///                         with VertexCount=0 on a map with no decals)
///   int32 IndexCount
///   int32 IndexOffset   (relative to this header's own start; same -1
///                         convention when empty)
///   Vertex[VertexCount] — 76 bytes each (verified against decal.hlsl's
///     VS_INPUT for STATIC decals, and against real baked ScaleOffset values
///     matching decalmats.tdf's named atlas rectangles exactly):
///       float3 Position
///       float3 TexCoord       — projected/clip-space decal-box coordinates
///       float4 ScaleOffset    — (rectW/atlasW, rectH/atlasH, rectX/atlasW, rectY/atlasH)
///       float3 TangentXform0  — tangent-space basis column (TANGENT)
///       float3 TangentXform1  — tangent-space basis column (BINORMAL)
///       float3 TangentXform2  — tangent-space basis column (NORMAL)
///   int32[IndexCount] — plain 32-bit indices, 3 per triangle (already
///     triangulated)
/// </summary>
/// <summary>Value type, not a class — a single decal preview rebuild
/// (SC2DecalGeometryBuilder.BuildPlacement) can emit tens of thousands of
/// these per stroke. Flat float fields instead of six separate float[]
/// arrays means a List&lt;DecalVertex&gt; stores every vertex inline in one
/// contiguous backing array, avoiding what was otherwise 7 heap allocations
/// (1 object + 6 arrays) per vertex — confirmed as one of the two dominant
/// costs in that rebuild's own measured timing, alongside
/// SC2DecalSurfaceTriangle's identical fix on the input side.</summary>
public struct DecalVertex
{
    public float PositionX, PositionY, PositionZ;
    public float TexCoordX, TexCoordY, TexCoordZ;
    public float ScaleOffsetX, ScaleOffsetY, ScaleOffsetZ, ScaleOffsetW;
    public float TangentXform0X, TangentXform0Y, TangentXform0Z;
    public float TangentXform1X, TangentXform1Y, TangentXform1Z;
    public float TangentXform2X, TangentXform2Y, TangentXform2Z;
}

public sealed class DecalsModel
{
    public int Version = 3;
    public string DiffuseAtlasPath = "";
    public string NormalAtlasPath = "";

    /// <summary>Serialized EDH/EDB spatial block. It stays raw here to retain
    /// byte-identical passthrough, while DecalsSpatialBuilder owns generation
    /// after geometry changes. Empty when the map has no decals.</summary>
    public byte[] ExtraDataRaw = Array.Empty<byte>();

    /// <summary>Absolute offset at which ExtraDataRaw was parsed or built.
    /// EDB pointers are absolute file offsets, so serialization rebases them
    /// when atlas-path lengths move the spatial block.</summary>
    public int ExtraDataOriginalStart = -1;

    /// <summary>Original container OffsetTable entries that fell inside
    /// ExtraDataRaw, stored relative to ExtraDataRaw's own start so they can
    /// be re-based onto wherever the block ends up on export. These mark
    /// pointer-valued fields inside the EDH/EDB tree. Generated blocks contain
    /// two child relocations per node followed by the ten EDH relocations.</summary>
    public uint[] ExtraDataOffsetTable = Array.Empty<uint>();

    public List<DecalVertex> Vertices = new();
    public List<int> Indices = new();

    public bool HasDecals => Vertices.Count > 0;
}

public static class DecalsBdf
{
    public static BdfPadding Padding => BdfPadding.Align32;
    private const int HeaderSize = 16;
    private const int VertexStride = 76;
    private const int GeometryHeaderSize = 20;

    public static DecalsModel Parse(BdfContainer container)
    {
        var data = container.Data;
        var r = new BdfReader(data, container.Platform);
        var model = new DecalsModel { Version = r.PeekInt32At(0) };

        if (data.Length < HeaderSize)
            return model; // degenerate/unrecognized — return an empty model rather than throw

        var diffuseOff = r.PeekInt32At(4);
        var normalOff = r.PeekInt32At(8);
        var extraOff = r.PeekInt32At(12);

        if (diffuseOff >= 0 && diffuseOff < data.Length)
            model.DiffuseAtlasPath = r.ReadCStringAt((uint)diffuseOff);
        if (normalOff >= 0 && normalOff < data.Length)
            model.NormalAtlasPath = r.ReadCStringAt((uint)normalOff);

        // No File#2 location known, or no decal content at all (extraOff ==
        // -1 is the confirmed "empty map" sentinel) — nothing more to read.
        if (container.TrailingData == null || container.TrailingData.Length < 8)
            return model;

        var h2 = (int)BitConverter.ToUInt32(container.TrailingData, 4);
        if (h2 <= 0 || h2 + GeometryHeaderSize > data.Length)
            return model;

        var vertexCount = r.PeekInt32At(h2 + 4);
        var vertexOffsetRel = r.PeekInt32At(h2 + 8);
        var indexCount = r.PeekInt32At(h2 + 12);
        var indexOffsetRel = r.PeekInt32At(h2 + 16);

        if (extraOff >= 0 && extraOff < h2)
        {
            model.ExtraDataRaw = data[extraOff..h2];
            model.ExtraDataOriginalStart = extraOff;
            model.ExtraDataOffsetTable = container.OffsetTable
                .Where(o => o >= extraOff && o < h2)
                .Select(o => o - (uint)extraOff)
                .ToArray();
        }

        if (vertexCount > 0 && vertexOffsetRel >= 0)
        {
            var vStart = h2 + vertexOffsetRel;
            for (var i = 0; i < vertexCount; i++)
            {
                var b = vStart + i * VertexStride;
                if (b + VertexStride > data.Length) break;
                model.Vertices.Add(new DecalVertex
                {
                    PositionX = r.PeekFloatAt(b), PositionY = r.PeekFloatAt(b + 4), PositionZ = r.PeekFloatAt(b + 8),
                    TexCoordX = r.PeekFloatAt(b + 12), TexCoordY = r.PeekFloatAt(b + 16), TexCoordZ = r.PeekFloatAt(b + 20),
                    ScaleOffsetX = r.PeekFloatAt(b + 24), ScaleOffsetY = r.PeekFloatAt(b + 28), ScaleOffsetZ = r.PeekFloatAt(b + 32), ScaleOffsetW = r.PeekFloatAt(b + 36),
                    TangentXform0X = r.PeekFloatAt(b + 40), TangentXform0Y = r.PeekFloatAt(b + 44), TangentXform0Z = r.PeekFloatAt(b + 48),
                    TangentXform1X = r.PeekFloatAt(b + 52), TangentXform1Y = r.PeekFloatAt(b + 56), TangentXform1Z = r.PeekFloatAt(b + 60),
                    TangentXform2X = r.PeekFloatAt(b + 64), TangentXform2Y = r.PeekFloatAt(b + 68), TangentXform2Z = r.PeekFloatAt(b + 72)
                });
            }
        }

        if (indexCount > 0 && indexOffsetRel >= 0)
        {
            var iStart = h2 + indexOffsetRel;
            for (var i = 0; i < indexCount; i++)
            {
                var b = iStart + i * 4;
                if (b + 4 > data.Length) break;
                model.Indices.Add(r.PeekInt32At(b));
            }
        }

        return model;
    }

    /// <summary>
    /// Round-trips byte-for-byte when neither atlas path's length nor the
    /// vertex/index data changed from what Parse() produced (the common
    /// "import, tweak unrelated things, export" case). If a path length
    /// changes, the EDH/EDB block necessarily shifts; Serialize rebases every
    /// non-null absolute pointer identified by ExtraDataOffsetTable.
    /// Call DecalsSpatialBuilder.Rebuild after editing Vertices/Indices; that
    /// operation also applies the geometry permutation described by the tree.
    /// </summary>
    public static (byte[] Data, uint[] OffsetTable, uint NumFiles, byte[] TrailingData) Serialize(DecalsModel model)
    {
        var w = new BdfWriter(BdfPlatform.Pc);
        var offsetTable = new List<uint>();

        var diffuseBytes = Encoding.ASCII.GetBytes(model.DiffuseAtlasPath ?? "");
        var normalBytes = Encoding.ASCII.GetBytes(model.NormalAtlasPath ?? "");
        var diffuseOff = HeaderSize;
        var normalOff = diffuseOff + diffuseBytes.Length + 1;
        var hasDecals = model.HasDecals;
        var minimumExtraOff = normalOff + normalBytes.Length + 1;
        var extraOff = hasDecals
            ? Math.Max(minimumExtraOff, model.ExtraDataOriginalStart)
            : -1;

        w.WriteInt32(model.Version);
        offsetTable.Add((uint)w.Position); w.WriteInt32(diffuseOff);
        offsetTable.Add((uint)w.Position); w.WriteInt32(normalOff);
        offsetTable.Add((uint)w.Position); w.WriteInt32(extraOff);

        w.WriteBytes(diffuseBytes); w.WriteByte(0);
        w.WriteBytes(normalBytes); w.WriteByte(0);
        while (hasDecals && w.Position < extraOff) w.WriteByte(0);

        int h2;
        if (hasDecals)
        {
            var extraDataStart = w.Position;
            w.WriteBytes(RebaseExtraData(model, extraDataStart));
            foreach (var relOffset in model.ExtraDataOffsetTable)
                offsetTable.Add((uint)(extraDataStart + relOffset));

            h2 = w.Position;
            w.WriteInt32(1); // geometry sub-file version, always 1
            w.WriteInt32(model.Vertices.Count);
            offsetTable.Add((uint)w.Position); w.WriteInt32(GeometryHeaderSize); // vertices start immediately after this 20-byte header
            w.WriteInt32(model.Indices.Count);
            var indexOffsetRel = GeometryHeaderSize + model.Vertices.Count * VertexStride;
            offsetTable.Add((uint)w.Position); w.WriteInt32(indexOffsetRel);

            foreach (var v in model.Vertices)
            {
                w.WriteFloat(v.PositionX); w.WriteFloat(v.PositionY); w.WriteFloat(v.PositionZ);
                w.WriteFloat(v.TexCoordX); w.WriteFloat(v.TexCoordY); w.WriteFloat(v.TexCoordZ);
                w.WriteFloat(v.ScaleOffsetX); w.WriteFloat(v.ScaleOffsetY); w.WriteFloat(v.ScaleOffsetZ); w.WriteFloat(v.ScaleOffsetW);
                w.WriteFloat(v.TangentXform0X); w.WriteFloat(v.TangentXform0Y); w.WriteFloat(v.TangentXform0Z);
                w.WriteFloat(v.TangentXform1X); w.WriteFloat(v.TangentXform1Y); w.WriteFloat(v.TangentXform1Z);
                w.WriteFloat(v.TangentXform2X); w.WriteFloat(v.TangentXform2Y); w.WriteFloat(v.TangentXform2Z);
            }
            foreach (var idx in model.Indices)
                w.WriteInt32(idx);
        }
        else
        {
            h2 = w.Position;
            w.WriteInt32(1);
            w.WriteInt32(0);
            offsetTable.Add((uint)w.Position); w.WriteInt32(-1);
            w.WriteInt32(0);
            offsetTable.Add((uint)w.Position); w.WriteInt32(-1);
        }

        var trailing = new byte[12];
        BitConverter.GetBytes(0u).CopyTo(trailing, 0);
        BitConverter.GetBytes((uint)h2).CopyTo(trailing, 4);
        BitConverter.GetBytes(0u).CopyTo(trailing, 8);

        return (w.ToArray(), offsetTable.ToArray(), 2u, trailing);
    }

    private static byte[] RebaseExtraData(DecalsModel model, int newStart)
    {
        var source = model.ExtraDataRaw ?? Array.Empty<byte>();
        var result = (byte[])source.Clone();
        if (model.ExtraDataOriginalStart < 0 || model.ExtraDataOriginalStart == newStart)
            return result;

        var delta = checked(newStart - model.ExtraDataOriginalStart);
        foreach (var relative in model.ExtraDataOffsetTable ?? Array.Empty<uint>())
        {
            if (relative > int.MaxValue || relative + 4u > result.Length)
                throw new InvalidOperationException($"Decals spatial relocation {relative} is outside the {result.Length}-byte block.");
            var offset = (int)relative;
            var value = BitConverter.ToUInt32(result, offset);
            if (value == uint.MaxValue) continue;
            var rebased = checked((uint)(checked((long)value + delta)));
            BitConverter.GetBytes(rebased).CopyTo(result, offset);
        }
        return result;
    }
}
